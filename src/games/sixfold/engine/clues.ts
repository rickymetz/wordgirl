export interface ClueEntry {
  text: string;
  /** A true cryptic (definition + wordplay) rather than a straight clue. */
  cryptic: boolean;
  /** For a cryptic: how the wordplay works. */
  how?: string;
}

/**
 * The clue for `word` on its `n`-th appearance: straight, then a second
 * straight clue, then a cryptic — and round again. A repeat day never
 * shows the last clue again, and one day in three is cryptic.
 */
export function clueFor(word: string, n = 0): ClueEntry {
  const straight = CLUES[word] ?? [];
  const cryptic = CRYPTIC[word];
  const rotation: ClueEntry[] = [
    ...straight.map((text) => ({ text, cryptic: false })),
    ...(cryptic ? [{ text: cryptic.clue, cryptic: true, how: cryptic.how }] : []),
  ];
  if (!rotation.length) return { text: "", cryptic: false };
  return rotation[((n % rotation.length) + rotation.length) % rotation.length];
}
